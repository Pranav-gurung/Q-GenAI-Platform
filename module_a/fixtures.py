"""Synthetic TEST FIXTURE generator. Output is software-test data, NOT industrial training data."""
from __future__ import annotations

import csv
import random
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

FIXTURE_CLASSES = ["fixture_line", "fixture_blob"]
FIXTURE_NOTICE = ("SYNTHETIC TEST FIXTURE generated by module_a.fixtures. Random shapes on noise. "
                  "Not real industrial imagery; must not be used to train or evaluate a production detector.")


def generate_fixture(root: Path, n_parts: int = 14, views_per_part: int = 3, size: int = 128, seed: int = 0) -> tuple:
    """Write images + annotations.csv under ``root``. Returns (image_dir, annotations_csv)."""
    rng = random.Random(seed)
    img_dir = Path(root) / "images"
    img_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for p in range(n_parts):
        base = np.random.default_rng(seed * 1000 + p).normal(128, 12, (size, size)).clip(0, 255).astype(np.uint8)
        n_def = rng.choice([0, 1, 1, 2])
        defects = []
        for _ in range(n_def):
            cls = rng.choice(FIXTURE_CLASSES)
            if cls == "fixture_line":
                x0, y0 = rng.randint(10, size - 50), rng.randint(10, size - 20)
                w, h = rng.randint(25, 40), rng.randint(3, 6)
            else:
                x0, y0 = rng.randint(10, size - 40), rng.randint(10, size - 40)
                w = h = rng.randint(10, 22)
            defects.append((cls, x0, y0, x0 + w, y0 + h))
        for v in range(views_per_part):
            arr = base.astype(np.int16) + np.random.default_rng(seed * 7919 + p * 31 + v).normal(0, 4, base.shape)
            im = Image.fromarray(arr.clip(0, 255).astype(np.uint8)).convert("RGB")
            d = ImageDraw.Draw(im)
            for cls, x0, y0, x1, y1 in defects:
                if cls == "fixture_line":
                    d.rectangle([x0, y0, x1 - 1, y1 - 1], fill=(235, 235, 235))
                else:
                    d.ellipse([x0, y0, x1 - 1, y1 - 1], fill=(40, 40, 40))
            name = f"part{p:03d}_view{v}.png"
            im.save(img_dir / name)
            if not defects:
                rows.append({"image": name, "group_id": f"part{p:03d}", "class": "", "xmin": "", "ymin": "", "xmax": "", "ymax": ""})
            for cls, x0, y0, x1, y1 in defects:
                rows.append({"image": name, "group_id": f"part{p:03d}", "class": cls,
                             "xmin": x0, "ymin": y0, "xmax": x1, "ymax": y1})
    ann = Path(root) / "annotations.csv"
    with open(ann, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["image", "group_id", "class", "xmin", "ymin", "xmax", "ymax"])
        w.writeheader()
        w.writerows(rows)
    (Path(root) / "FIXTURE_NOTICE.txt").write_text(FIXTURE_NOTICE + "\n")
    return img_dir, ann
